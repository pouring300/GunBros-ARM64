#!/usr/bin/env python3
"""Generate include/gunbros/compatibility/icon_patches.h: the Discord logo, sized for each
Facebook icon in the game's UI atlases, which the bridge paints in when the atlas is uploaded
(see src/hle/gles1.c).

usage: gen_icon_patches.py <atlas dump dir> > include/gunbros/compatibility/icon_patches.h

The atlas dump dir holds raw RGBA uploads named tex_NNNN_<w>x<h>_1908_1401.raw (written by a
debug build); they're only used to fingerprint the original icon pixels. Needs Pillow.
"""
import os, sys
from PIL import Image, ImageDraw

LOGO = os.path.join(os.path.dirname(__file__), '..', 'resources', 'discord_logo.png')

# (atlas file, atlas width, atlas height, x, y, w, h, corner radius): the Facebook icon's blue
# area in each atlas (texture row order, i.e. upside down), inset to keep its frame.
PATCHES = [
    ('tex_0009_1024x1024_1908_1401.raw', 1024, 1024, 299, 42, 58, 58, 6),    # side button
    ('tex_0009_1024x1024_1908_1401.raw', 1024, 1024, 431, 484, 58, 58, 6),   # side button, lit
    ('tex_0037_1024x512_1908_1401.raw', 1024, 512, 135, 153, 108, 108, 16),  # large icon
]

def fnv1a(data):
    h = 0x811c9dc5
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xffffffff
    return h

def region(raw, aw, x, y, w, h):
    return b''.join(raw[((y + r) * aw + x) * 4:((y + r) * aw + x + w) * 4] for r in range(h))

def main():
    dump = sys.argv[1]
    logo = Image.open(LOGO).convert('RGBA')
    out = ['/* Generated by scripts/gen_icon_patches.py from resources/discord_logo.png. Do not edit. */',
           '#ifndef GUNBROS_ICON_PATCHES_H', '#define GUNBROS_ICON_PATCHES_H', '', '#include <stdint.h>', '']
    entries = []
    for n, (name, aw, ah, x, y, w, h, radius) in enumerate(PATCHES):
        raw = open(os.path.join(dump, name), 'rb').read()
        fingerprint = fnv1a(region(raw, aw, x, y, w, h))
        img = logo.resize((w, h), Image.LANCZOS)
        mask = Image.new('L', (w, h), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, w - 1, h - 1), radius, fill=255)
        img.putalpha(mask)
        # Composite onto the original pixels so the rounded corners keep what was there.
        orig = Image.frombytes('RGBA', (w, h), region(raw, aw, x, y, w, h)).transpose(Image.FLIP_TOP_BOTTOM)
        orig.alpha_composite(img)
        pixels = orig.transpose(Image.FLIP_TOP_BOTTOM).tobytes()
        out.append(f'static const uint8_t s_icon_patch_{n}[{len(pixels)}] = {{')
        for i in range(0, len(pixels), 24):
            out.append('    ' + ', '.join(f'0x{b:02x}' for b in pixels[i:i + 24]) + ',')
        out.append('};')
        entries.append(f'    {{ {aw}, {ah}, {x}, {y}, {w}, {h}, 0x{fingerprint:08x}u, s_icon_patch_{n} }},')
    out += ['', 'typedef struct {', '    uint32_t atlas_w, atlas_h, x, y, w, h;',
            '    uint32_t fingerprint;  /* FNV-1a of the original icon pixels */',
            '    const uint8_t *rgba;', '} icon_patch_t;', '',
            'static const icon_patch_t s_icon_patches[] = {'] + entries + ['};', '', '#endif // GUNBROS_ICON_PATCHES_H', '']
    print('\n'.join(out))

main()
